  await page.waitForFunction(()=>document.querySelector('#collector-custom-interval').value==='0.75');
  await verify();await preview('继续下一轮');await page.locator('#collector-confirm').click();
  await page.locator('#collector-pause').click();
  await page.waitForFunction(()=>document.querySelector('#collector-start').textContent==='继续采集'&&!document.querySelector('#collector-start').disabled);
  assert.equal((await state()).job.id,original.id);
  await stop();await start();await page.goto(base+'/'+query+'#collector-panel');await ready();await verify();
  await preview('继续任务');await page.locator('#collector-confirm').click();await awaitRound();
