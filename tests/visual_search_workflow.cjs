  await start();browser=await chromium.launch({headless:true,channel:'chrome'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',route=>{
    const url=new URL(route.request().url());
    return url.hostname==='127.0.0.1'&&!url.pathname.startsWith('/api/cover/')?route.continue():route.abort();
  });
  const query='?tag=language%3Aenglish&tag=other%3Asample&tag_mode=or&sort=newest';
  const ready=()=>page.waitForFunction(()=>document.querySelector('#results[aria-busy="false"] .saved-card'));
  const state=async()=>await(await page.request.get(base+'/api/collector')).json();
  const apply=async()=>{
    await page.locator('#collector-save').click();
    await page.waitForFunction(()=>document.querySelector('#collector-feedback').textContent.startsWith('设置已应用')&&!document.querySelector('#collector-start').disabled);
  };
  const verify=async()=>{
    await page.locator('#collector-verify').click();
    await page.waitForFunction(()=>/随机验证成功|当前条件没有需要抓取/.test(document.querySelector('#collector-feedback').textContent)&&!document.querySelector('#collector-start').disabled);
  };
  const preview=async operation=>{
    await page.locator('#collector-start').click();
    await page.waitForFunction(()=>!document.querySelector('#collector-estimate').hidden&&!document.querySelector('#collector-confirm').disabled);
    assert((await page.locator('#estimate-scope').textContent()).includes(operation));
  };
  const awaitRound=()=>page.waitForFunction(()=>document.querySelector('#collector-next-round').hidden===false&&!document.querySelector('#collector-start').disabled);
  await page.goto(base+'/'+query);await ready();
  assert((await page.locator('#results-summary').textContent()).includes('97'));
  await page.locator('#tag-mode').selectOption('and');await page.locator('#search-button').click();await ready();
  assert((await page.locator('#results-summary').textContent()).includes('共 1 条'));
  await page.locator('#tag-mode').selectOption('or');await page.locator('#search-button').click();await ready();
  await page.locator('#next').click();
  await page.waitForFunction(()=>document.querySelector('#page-input').value==='2'&&document.querySelector('#results').getAttribute('aria-busy')==='false');
  await page.locator('#search-view').selectOption('compact');
  await page.waitForFunction(()=>!document.querySelector('#search-view').disabled);
  await page.locator('#title-input').fill('尚未提交的标题');
  await page.locator('#results-heading').scrollIntoViewIfNeeded();
  await page.evaluate(()=>scrollTo({top:900,behavior:'instant'}));
  await page.goto(base+'/records');
  await page.waitForSelector('#records-list .saved-card');
  await page.locator('.sidebar .nav-item[href="/"]').click();await ready();
  assert.equal(await page.locator('#page-input').inputValue(),'2');
  assert.equal(await page.locator('#tag-mode').inputValue(),'or');
  assert.equal(await page.locator('#title-input').inputValue(),'尚未提交的标题');
  assert(!new URL(page.url()).searchParams.has('title'),'Unsubmitted draft changed the result scope');
  assert.equal(await page.locator('#search-view').inputValue(),'compact');
  await page.waitForFunction(()=>scrollY>200);
  await page.goto(base+'/records'+query);
  await page.waitForFunction(()=>document.querySelector('#records-list').getAttribute('aria-busy')==='false');
  assert.equal(await page.locator('#record-tag-mode').inputValue(),'or');
  await page.locator('.sidebar .nav-item[href="/"]').click();await ready();
  await page.locator('#title-input').fill('');
  await page.locator('#collector-panel').evaluate(node=>node.open=true);
  await page.waitForFunction(()=>!document.querySelector('#collector-interval').disabled);
  await page.locator('#collector-interval').selectOption('0.5');await apply();
  await page.reload();await ready();
  await page.waitForFunction(()=>document.querySelector('#collector-interval').value==='0.5');
  await page.locator('#collector-interval').selectOption('custom');
