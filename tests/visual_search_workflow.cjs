  await page.reload();await ready();
  await page.waitForFunction(()=>document.querySelector('#collector-interval').value==='custom'&&document.querySelector('#collector-custom-interval').value==='1.25');
  await page.locator('#collector-custom-interval').fill('0.4');
  assert.equal(await page.locator('#collector-custom-interval').evaluate(node=>node.checkValidity()),false);
  await page.locator('#collector-custom-interval').fill('0.75');
  await page.locator('#collector-mode').selectOption('rounds');
  await page.locator('#collector-batch-size').selectOption('custom');
  await page.locator('#collector-custom-batch-size').fill('10');await apply();await verify();
